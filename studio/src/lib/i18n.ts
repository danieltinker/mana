import { signal } from '@preact/signals';
import { PRODUCT } from '../product.ts';

export type Lang = 'he' | 'en';
function initial(): Lang {
  try { const s = localStorage.getItem('mana-studio-lang'); if (s === 'he' || s === 'en') return s; } catch { /* storage is optional */ }
  return 'he';
}
export const lang = signal<Lang>(initial());
export function setLang(l: Lang) {
  lang.value = l;
  try { localStorage.setItem('mana-studio-lang', l); } catch { /* storage is optional */ }
  applyLang();
}
export function applyLang() {
  document.documentElement.lang = lang.value;
  document.documentElement.dir = lang.value === 'he' ? 'rtl' : 'ltr';
}

