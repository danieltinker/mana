export function t(key: string, vars?: Record<string, string | number>): string {
  const pair = S[key];
  let s = pair ? pair[lang.value === 'he' ? 0 : 1] : key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
/** Counted sentences: uses the '<key>1' wording when n is exactly one (Hebrew and English both need it). */
export const tn = (key: string, n: number, vars: Record<string, string | number> = {}) => t(n === 1 && key + '1' in S ? key + '1' : key, { n, ...vars });
export const has = (key: string) => key in S;
export const KEYS = Object.keys(S);
export const productMark = PRODUCT.mark;

export function fmtDate(d: Date | string | null | undefined): string {
  if (!d) return '';
  const date = typeof d === 'string' ? new Date(d) : d;
  try { return new Intl.DateTimeFormat(lang.value === 'he' ? 'he-IL' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' }).format(date); }
  catch { return date.toISOString().slice(0, 10); }
}
export function fmtDateTime(d: Date | string): string {
  const date = typeof d === 'string' ? new Date(d) : d;
  try { return new Intl.DateTimeFormat(lang.value === 'he' ? 'he-IL' : 'en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }).format(date); }
  catch { return date.toISOString().slice(0, 16).replace('T', ' '); }
}
export const errText = (code: string, scope?: string) => (scope && has(scope + '.' + code) ? t(scope + '.' + code) : has('err.' + code) ? t('err.' + code) : t('err.unknown'));
