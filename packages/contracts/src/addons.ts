/**
 * Saving an add-on group in one call: the group and its whole list of options (`save_addon_group`, ADR-008).
 *
 * Phase 0's editor saved a group as several writes (options deleted first, then updated, then inserted), so a refusal
 * or a dropped connection left the group half-saved and a retry created duplicates. The RPC does it in one transaction,
 * and the ids are the client's, so a retry is harmless.
 *
 * The group and its options travel as their table rows (snake_case, the columns the owner may set), the way the editor
 * reads them from the tables. `validateAddonGroupInput` is the twin of the database's `app.validate_addon_group_input`
 * (same codes, same paths, same first issue); `validateAddonGroup` runs the same checks on one group and its options for
 * the editor's form; `addonGroupMenuIssues` runs, on the editor's loaded menu, the checks the RPC makes against stored
 * rows.
 */
import { Issues, isBlank, isInt, isObject, isString, isUuid, oneOf, type Issue, type Validation } from './common.ts';
import type { AddonGroupRow, AddonOptionRow } from './domain.ts';
import { LIMITS, SELECTIONS } from './enums.ts';
import { GROUP_UNITS_MAX } from './import.ts';
import { onlyKeys, optionalText } from './rpc.ts';

/** A group's label and names, an option's names: the schema's 60 code points. */
export const ADDON_TEXT_MAX = 60;
/** The largest `position` the RPC accepts for an option. */
export const ADDON_POSITION_MAX = 100_000;

/**
 * The group's whole state as the editor saves it. `id` is generated by the client (`crypto.randomUUID()`) for a new
 * group and kept for every later save: absent in the table → inserted; present → updated. A key left out takes the
 * table's default (label and names '', selection 'single', min 0, max 1); `limits_confirmed` left out keeps the stored
 * value (true for a new group). The column `limits_confirmed` arrives with the phase-1 migration.
 */
export type AddonGroupWrite = Pick<AddonGroupRow, 'id'> &
  Partial<Pick<AddonGroupRow, 'label' | 'name_he' | 'name_en' | 'selection' | 'min_units' | 'max_units'>> & { readonly limits_confirmed?: boolean };

/** One option, with a client-generated id like the group's. A key left out takes the table's default (names '', price
 * 0, max_qty 1, is_default false, opens_group_id null); `position` left out is the option's index in the list. */
export type AddonOptionWrite = Pick<AddonOptionRow, 'id'> &
  Partial<Pick<AddonOptionRow, 'position' | 'name_he' | 'name_en' | 'price' | 'max_qty' | 'is_default' | 'opens_group_id'>>;

/**
 * `save_addon_group(p_venue uuid, p_group jsonb, p_options jsonb, p_expected_updated_at timestamptz default null,
 * p_confirm_rule_removal boolean default false)` → `SaveAddonGroupReply`. Who: owner, manager (`app.can_edit`; anyone
 * else gets 42501 `not_allowed`, raised).
 *
 * In this order (a failure answers one code, with the `path` of what to fix where there is one):
 *
 * 1. `venue_unknown` (no such venue, or archived).
 * 2. `app.validate_addon_group_input({venueId, group, options})`: the first issue of `validateAddonGroupInput`.
 * 3. Then one transaction under the venue's nesting advisory lock (the one `app.guard_nesting` takes).
 * 4. `not_allowed` with `group.id` (the id is another venue's group) or `options[i].id` (an option of another venue or
 *    another group: an option never moves between groups); `group_unknown` with `options[i].opens_group_id` (it opens a
 *    group the venue does not have).
 * 5. The input is read as the triggers will store it (blank edges stripped, the defaults above). When the group exists:
 *    - **an input equal to what is stored** (the group's columns, and exactly its options with the same columns) is
 *      `ok` and writes nothing, whatever version was sent, so a retry after a lost answer succeeds;
 *    - **a differing input** whose `p_expected_updated_at` is absent or is not the group's `updated_at` is `stale`, with
 *      `current` (the stored group and options). The group's `updated_at` versions its options too: it moves whenever
 *      the RPC changes the group or any of its options. It is compared as `timestamptz`, so the client sends the value
 *      exactly as it read it (a table read and this reply give microseconds).
 *    A group that does not exist is inserted, whatever version was sent (a group deleted elsewhere is created again).
 * 6. `option_in_rules` with `rules` (ids, sorted): options the input leaves out are suggested by upsell rules. With
 *    `p_confirm_rule_removal` the save goes on and those rules are deleted with the options (the foreign key's
 *    cascade; the audit logs each deletion).
 * 7. The writes, `via = rpc`, audited per statement: the group inserted or updated (changing `min_units` or `max_units`
 *    sets `limits_confirmed`; otherwise the input's `limits_confirmed`, when given, is stored); the left-out options
 *    deleted; the options inserted or updated (only those that differ); the group's `updated_at` touched when only its
 *    options changed (not logged as activity).
 * 8. A trigger that refuses a row rolls the whole save back and answers its code: `nesting_too_deep`,
 *    `limit_options_per_group`, `limit_addon_groups`, `limits_loosened`, …; a foreign key `group_unknown`, a unique key
 *    `conflict`, another check `invalid` (with the `constraint`'s name).
 *
 * The reply's rows are the stored rows as `to_jsonb` gives them; options by `position`, then `id`.
 */
export type SaveAddonGroupInput = {
  readonly venueId: string;
  readonly group: AddonGroupWrite;
  readonly options: readonly AddonOptionWrite[];
  /** The group's `updated_at` as the editor last read it; null for a group the editor is creating. */
  readonly expectedUpdatedAt: string | null;
  /** Delete the upsell rules that suggest a deleted option (after an `option_in_rules` answer). Default false. */
  readonly confirmRuleRemoval?: boolean;
};

/** What `validateAddonGroupInput` checks (and the database's twin): the save without its version and confirmation. */
export type AddonGroupCheck = Pick<SaveAddonGroupInput, 'venueId' | 'group' | 'options'>;

/** The codes of `validateAddonGroupInput` / `validateAddonGroup`. `text_invalid` (NUL, half an emoji) is the
 * contracts' only: such text cannot reach the database as JSON at all. */
export type AddonGroupCode =
  | 'type' | 'field_not_allowed' | 'id_invalid' | 'id_duplicate' | 'text_too_long' | 'text_invalid' | 'name_missing'
  | 'enum_invalid' | 'units_invalid' | 'single_max' | 'price_invalid' | 'qty_invalid' | 'position_invalid'
  | 'nesting_invalid' | 'defaults_invalid';

/** The codes the database finds against stored rows (steps 4, 6 and 8 above). */
export type SaveAddonGroupStoredCode =
  | 'venue_unknown' | 'not_allowed' | 'group_unknown' | 'nesting_too_deep' | 'limit_options_per_group' | 'limit_addon_groups'
  | 'limits_loosened' | 'conflict' | 'invalid';

export type StoredAddonGroup = { readonly group: AddonGroupRow; readonly options: readonly AddonOptionRow[] };

export type SaveAddonGroupReply =
  | ({ readonly ok: true } & StoredAddonGroup)
  | { readonly ok: false; readonly code: 'stale'; readonly current: StoredAddonGroup }
  | { readonly ok: false; readonly code: 'option_in_rules'; readonly rules: readonly string[] }
  | { readonly ok: false; readonly code: AddonGroupCode | SaveAddonGroupStoredCode; readonly path?: string; readonly constraint?: string };

const GROUP_KEYS: readonly string[] = ['id', 'label', 'name_he', 'name_en', 'selection', 'min_units', 'max_units', 'limits_confirmed'];
const OPTION_KEYS: readonly string[] = ['id', 'position', 'name_he', 'name_en', 'price', 'max_qty', 'is_default', 'opens_group_id'];

/** A key the input has, as JSON carries it (a key whose value is `undefined` does not reach the database). */
const given = (o: Readonly<Record<string, unknown>>, k: string): boolean => Object.prototype.hasOwnProperty.call(o, k) && o[k] !== undefined;
const between = (v: unknown, lo: number, hi: number): boolean => isInt(v) && v >= lo && v <= hi;
const blankName = (o: Readonly<Record<string, unknown>>): boolean =>
  isBlank(isString(o.name_he) ? o.name_he : '') && isBlank(isString(o.name_en) ? o.name_en : '');

/** The group and options checks, in the twin's order. */
function check(x: Issues, g: unknown, options: unknown): void {
  let gid: string | null = null;
  let hi: number | null = null;
  if (!isObject(g)) x.add('type', 'group');
  else {
    for (const k of Object.keys(g)) if (!GROUP_KEYS.includes(k)) x.add('field_not_allowed', `group.${k}`);
    if (isUuid(g.id)) gid = g.id.toLowerCase();
    else x.add('id_invalid', 'group.id');
    optionalText(x, g.label, 'group.label', ADDON_TEXT_MAX);
    optionalText(x, g.name_he, 'group.name_he', ADDON_TEXT_MAX);
    optionalText(x, g.name_en, 'group.name_en', ADDON_TEXT_MAX);
    if (blankName(g)) x.add('name_missing', 'group');
    if (given(g, 'selection') && !oneOf(SELECTIONS, g.selection)) x.add('enum_invalid', 'group.selection');
    if (given(g, 'min_units') && !between(g.min_units, 0, GROUP_UNITS_MAX)) x.add('units_invalid', 'group.min_units');
    else if (given(g, 'max_units') && !between(g.max_units, 1, GROUP_UNITS_MAX)) x.add('units_invalid', 'group.max_units');
    else {
      hi = given(g, 'max_units') ? (g.max_units as number) : 1;
      const lo = given(g, 'min_units') ? (g.min_units as number) : 0;
      const single = !given(g, 'selection') || g.selection === null || g.selection === 'single';
      if (lo > hi) x.add('units_invalid', 'group.max_units');
      else if (single && hi !== 1) x.add('single_max', 'group.max_units');
    }
    if (given(g, 'limits_confirmed') && typeof g.limits_confirmed !== 'boolean') x.add('type', 'group.limits_confirmed');
  }

  if (!Array.isArray(options)) return void x.add('type', 'options');
  const ids = new Set<string>();
  let defaults = 0;
  options.forEach((o: unknown, i) => {
    const at = `options[${i}]`;
    if (!isObject(o)) return void x.add('type', at);
    for (const k of Object.keys(o)) if (!OPTION_KEYS.includes(k)) x.add('field_not_allowed', `${at}.${k}`);
    if (!isUuid(o.id)) x.add('id_invalid', `${at}.id`);
    else if (ids.has(o.id.toLowerCase())) x.add('id_duplicate', `${at}.id`);
    else ids.add(o.id.toLowerCase());
    if (given(o, 'position') && !between(o.position, 0, ADDON_POSITION_MAX)) x.add('position_invalid', `${at}.position`);
    optionalText(x, o.name_he, `${at}.name_he`, ADDON_TEXT_MAX);
    optionalText(x, o.name_en, `${at}.name_en`, ADDON_TEXT_MAX);
    if (blankName(o)) x.add('name_missing', at);
    if (given(o, 'price') && !between(o.price, 0, LIMITS.price)) x.add('price_invalid', `${at}.price`);
    const opens = given(o, 'opens_group_id') && o.opens_group_id !== null;
    if (given(o, 'max_qty') && !between(o.max_qty, 1, LIMITS.optionQuantity)) x.add('qty_invalid', `${at}.max_qty`);
    else if (opens && (given(o, 'max_qty') ? o.max_qty : 1) !== 1) x.add('qty_invalid', `${at}.max_qty`);
    if (given(o, 'is_default') && typeof o.is_default !== 'boolean') x.add('type', `${at}.is_default`);
    else if (o.is_default === true) defaults += 1;
    if (opens) {
      if (!isUuid(o.opens_group_id)) x.add('id_invalid', `${at}.opens_group_id`);
      else if (o.opens_group_id.toLowerCase() === gid) x.add('nesting_invalid', `${at}.opens_group_id`);
    }
  });
  if (hi !== null && defaults > hi) x.add('defaults_invalid', 'options');
}

/**
 * `save_addon_group`'s input without its version and confirmation (`{venueId, group, options}`), checked as the
 * database's `app.validate_addon_group_input` checks it: the same issues, and the same first issue (the code the RPC
 * answers). Codes: `AddonGroupCode`. Paths: `venueId`, `group`, `group.<column>`, `options`, `options[i]`,
 * `options[i].<column>`.
 * - `units_invalid`: min not 0–30 (`group.min_units`), max not 1–30, or min above max (`group.max_units`);
 * - `single_max`: a single group (the default) whose max is not 1;
 * - `qty_invalid`: max_qty not 1–10, or an option that opens a group with max_qty other than 1;
 * - `nesting_invalid`: an option opens its own group; `defaults_invalid`: more defaults than the group's max;
 * - `name_missing`: neither name says anything (`group`, `options[i]`); `text_too_long`: above 60 code points once
 *   blank edges are stripped.
 * An empty list of options is valid here (publishing refuses an empty group, `options_empty`).
 */
export function validateAddonGroupInput(raw: unknown): Validation<AddonGroupCheck> {
  if (!isObject(raw)) return { ok: false, errors: [{ code: 'type', path: '' }] };
  const x = new Issues();
  onlyKeys(x, raw, ['venueId', 'group', 'options']);
  if (!isUuid(raw.venueId)) x.add('id_invalid', 'venueId');
  check(x, raw.group, raw.options);
  return x.ok ? { ok: true, value: raw as AddonGroupCheck } : { ok: false, errors: x.list };
}

/** The same checks on one group and its options, for the editor's form (paths as above). */
export function validateAddonGroup(group: unknown, options: unknown): Validation<{ group: AddonGroupWrite; options: readonly AddonOptionWrite[] }> {
  const x = new Issues();
  check(x, group, options);
  return x.ok ? { ok: true, value: { group: group as AddonGroupWrite, options: options as readonly AddonOptionWrite[] } } : { ok: false, errors: x.list };
}

/** The stored rows the menu checks read (the editor's loaded menu has these keys). */
export type AddonGroupMenu = {
  readonly groups: ReadonlyArray<Pick<AddonGroupRow, 'id'>>;
  readonly options: ReadonlyArray<Pick<AddonOptionRow, 'id' | 'group_id' | 'opens_group_id'>>;
};

/**
 * What the RPC would refuse against the venue's stored rows, found on the editor's copy of them before the call (every
 * one, where the RPC answers the first): `not_allowed` (`options[i].id` is an option of another group),
 * `group_unknown` (`options[i].opens_group_id` is not one of the venue's groups) and `nesting_too_deep` (an option
 * opens a group whose options open one, or this group holds an opener while an option of another group opens it). The
 * group's own stored options are left out, since the input replaces them. Run it on an input that passed
 * `validateAddonGroup`.
 */
export function addonGroupMenuIssues(group: AddonGroupWrite, options: readonly AddonOptionWrite[], menu: AddonGroupMenu): Issue[] {
  const x = new Issues();
  const gid = group.id.toLowerCase();
  const others = menu.options.filter((s) => s.group_id.toLowerCase() !== gid);
  const otherIds = new Set(others.map((s) => s.id.toLowerCase()));
  const groupIds = new Set(menu.groups.map((g) => g.id.toLowerCase()));
  const opened = others.some((s) => s.opens_group_id !== null && s.opens_group_id.toLowerCase() === gid);
  const openers = new Set(others.filter((s) => s.opens_group_id !== null).map((s) => s.group_id.toLowerCase()));
  options.forEach((o, i) => {
    if (otherIds.has(o.id.toLowerCase())) x.add('not_allowed', `options[${i}].id`);
    const t = o.opens_group_id?.toLowerCase();
    if (!t || t === gid) return;
    if (!groupIds.has(t)) x.add('group_unknown', `options[${i}].opens_group_id`);
    else if (opened || openers.has(t)) x.add('nesting_too_deep', `options[${i}].opens_group_id`);
  });
  return x.list;
}
