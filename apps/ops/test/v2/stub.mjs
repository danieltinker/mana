// A local stand-in for a schema-2 Supabase project, for the v2 back office's browser tests and for looking at it: the
// calls supabase-js makes for password sign-in, the caller's own staff row, and the staff RPCs, answered by the typed
// fake (fake.ts, contract-valid shapes). It serves dist/ at /mana/ops/ with a config that says schema 2, realtime off.
// Start: `npm run serve:v2` → http://127.0.0.1:8788/mana/ops/ (the accounts are below; they exist only in this stub).
import http from 'node:http';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MEDIA_BASE, USERS, addTraffic, fakeBackend, ownerEdit, ownerStep, padLog, publish, restore, world } from './fake.ts';
import { newSecret, totp } from './totp.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DIST = path.join(root, 'dist');
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.woff2': 'font/woff2', '.txt': 'text/plain; charset=utf-8' };
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString('base64url');
/** The menu pictures' bucket in a Supabase project (the database's public_base). */
const BUCKET = '/storage/v1/object/public/menu-public/';
const PIXEL = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==', 'base64');

/** Test accounts of this stub only (localhost). */
export const ACCOUNTS = {
  admin: { email: 'admin@halom.test', password: 'stub-admin-pass', id: USERS.admin },
  support: { email: 'support@halom.test', password: 'stub-support-pass', id: USERS.support },
  owner: { email: 'owner@cafe.test', password: 'stub-owner-pass', id: USERS.owner },
};
/** The staff RPCs: the ones `staff_require_aal2` closes to a password-only session. */
const STAFF_RPC = new Set(['ops_venues', 'ops_venue', 'ops_analytics', 'ops_update_case', 'ops_set_demo', 'ops_approve_venue', 'act_for_owner', 'ops_set_plan', 'ops_leads', 'ops_update_lead']);

/** The QR code Supabase Auth returns with a TOTP enrollment: an SVG (auth-js prefixes `data:image/svg+xml;utf-8,`). This
 * one carries a script and `#` colours: shown as an image it must run nothing, and its markup must never reach the page. */
const QR_SVG = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg" width="29" height="29" viewBox="0 0 29 29"><script>window.__xss=1</script>'
  + '<rect width="29" height="29" fill="#fff"/><path d="M1 1h7v7H1zM21 1h7v7h-7zM1 21h7v7H1zM11 11h7v7h-7z" fill="#000"/></svg>';

export function createStub() {
  // factors: user id → [{ id, friendly_name, factor_type, status, secret, created_at }]; mfaLimit: answers 429 that many times
  // enrollDelay: milliseconds Auth takes to answer an enrollment (a slow network while setting up)
  const S = { w: world(), tokens: new Map(), requireAal2: false, factors: new Map(), mfaLimit: 0, nextFactor: 1, enrollDelay: 0 };
  const reset = ({ traffic = true } = {}) => { S.w = world({ traffic }); S.tokens.clear(); S.requireAal2 = false; S.factors.clear(); S.mfaLimit = 0; S.enrollDelay = 0; };
  const factorsOf = (id) => { if (!S.factors.has(id)) S.factors.set(id, []); return S.factors.get(id); };
  // what Supabase Auth shows of a factor (never its secret)
  const shown = (f) => ({ id: f.id, friendly_name: f.friendly_name, factor_type: f.factor_type, status: f.status, created_at: f.created_at, updated_at: f.created_at });
  const authError = (res, status, code, msg) => json(res, status, { code: status, error_code: code, msg });

  const json = (res, status, body) => {
    if (res.writableEnded) return;
    res.writeHead(status, { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' });
    res.end(JSON.stringify(body));
  };
  const body = (req) => new Promise((resolve) => { let s = ''; req.on('data', (c) => { s += c; }); req.on('end', () => { try { resolve(s ? JSON.parse(s) : {}); } catch { resolve({}); } }); });
  const userOf = (a) => ({ id: a.id, aud: 'authenticated', role: 'authenticated', email: a.email, app_metadata: { provider: 'email' }, user_metadata: {},
    created_at: '2026-10-01T00:00:00Z', factors: factorsOf(a.id).map(shown) });
  /** A session at `aal` ('aal1' after a password, 'aal2' after the second step), its access token known to this stub. */
  const session = (a, aal = 'aal1') => {
    const now = Math.floor(Date.now() / 1000);
    const access = `${b64({ alg: 'HS256', typ: 'JWT' })}.${b64({ sub: a.id, email: a.email, role: 'authenticated', aud: 'authenticated', aal, amr: [{ method: aal === 'aal2' ? 'totp' : 'password', timestamp: now }], exp: now + 3600, iat: now })}.stub${Math.random().toString(36).slice(2)}`;
    S.tokens.set(access, { ...a, aal });
    return { access_token: access, token_type: 'bearer', expires_in: 3600, expires_at: now + 3600, refresh_token: 'r-' + access.slice(-12), user: userOf(a) };
  };
  const who = (req) => S.tokens.get((req.headers.authorization || '').replace(/^Bearer /, '')) ?? null;

  const server = http.createServer(async (req, res) => {
    const url = new URL(req.url, 'http://x');
    const p = url.pathname;
    try {
      if (p === '/__stub/control' && req.method === 'POST') {
        const c = await body(req);
        if (c.reset) S.w = world(c.reset === true ? {} : c.reset);           // new data; the signed-in sessions stay
        if (c.faults) S.w.faults = c.faults;
        if (c.delays) S.w.delays = c.delays;                                  // { fn: ms }: a slow database
        if (c.publish) publish(S.w, c.publish);                               // the owner publishes again
        if (c.restore) restore(S.w, c.restore.venueId, c.restore.revision);   // the owner goes back to an earlier revision
        if (c.ownerEdit) ownerEdit(S.w, c.ownerEdit.dishId, c.ownerEdit.patch); // the owner changes a dish in the owner app
        if (c.padLog) padLog(S.w, c.padLog.venueId, c.padLog.n);              // a long history
        if (c.ownerStep) ownerStep(S.w, c.ownerStep.venueId, c.ownerStep.step, c.ownerStep.state); // the owner marks a step
        if (c.approve) {                                                      // as if Halom had approved earlier
          const v = S.w.venues.find((x) => x.row.id === c.approve);
          if (v) { v.row.review = 'approved'; v.row.approvedAt = new Date().toISOString(); v.row.plan.state = 'trialing'; v.row.warnings = v.row.warnings.filter((x) => x !== 'awaiting_review'); }
        }
        if (c.requireAal2 !== undefined) S.requireAal2 = c.requireAal2;
        if (c.traffic) addTraffic(S.w, c.traffic.venueId, c.traffic.counts);
        if (c.revokeStaff) S.w.staff.delete(c.revokeStaff);
        // a TOTP factor set up earlier (verified unless said), and Supabase Auth's rate limit on the next verifies
        if (c.factor) factorsOf(c.factor.userId).push({ id: `00000000-0000-4000-8000-${String(0xf000 + S.nextFactor++).padStart(12, '0')}`,
          friendly_name: c.factor.name ?? 'Mana back office', factor_type: 'totp', status: c.factor.status ?? 'verified', secret: c.factor.secret, created_at: new Date().toISOString() });
        if (c.mfaRateLimit !== undefined) S.mfaLimit = c.mfaRateLimit;
        if (c.enrollDelay !== undefined) S.enrollDelay = c.enrollDelay;
        if (c.supportCanAct) { const v = S.w.venues.find((x) => x.row.id === c.supportCanAct.venueId); if (v) v.row.supportCanAct = c.supportCanAct.value; }
        return json(res, 200, { ok: true, calls: S.w.calls });
      }
      if (p === '/auth/v1/token' && req.method === 'POST') {
        const a = await body(req);
        if (url.searchParams.get('grant_type') === 'password') {
          const acc = Object.values(ACCOUNTS).find((x) => x.email === String(a.email || '').toLowerCase());
          if (!acc || acc.password !== a.password) return json(res, 400, { code: 400, error_code: 'invalid_credentials', msg: 'Invalid login credentials' });
          return json(res, 200, session(acc));
        }
        return json(res, 400, { code: 400, error_code: 'refresh_token_not_found', msg: 'Invalid Refresh Token' });
      }
      if (p === '/auth/v1/logout') { res.writeHead(204); return res.end(); }
      if (p === '/auth/v1/user') { const a = who(req); return a ? json(res, 200, userOf(a)) : json(res, 401, { code: 401, msg: 'invalid JWT' }); }
      // ---- the second step (MFA, TOTP), as Supabase Auth answers it
      if (p === '/auth/v1/factors' && req.method === 'POST') {
        const a = who(req);
        if (!a) return authError(res, 401, 'no_authorization', 'invalid JWT');
        const b = await body(req);
        S.w.calls.push({ fn: 'mfa.enroll', args: { friendly_name: b.friendly_name, factor_type: b.factor_type }, user: a.id });
        if (S.enrollDelay) await new Promise((r) => setTimeout(r, S.enrollDelay));
        if (b.factor_type !== 'totp') return authError(res, 422, 'validation_failed', 'factor_type must be totp here');
        const mine = factorsOf(a.id);
        if (b.friendly_name && mine.some((f) => f.friendly_name === b.friendly_name)) {
          return authError(res, 422, 'mfa_factor_name_conflict', `A factor with the friendly name "${b.friendly_name}" for this user already exists`);
        }
        const f = { id: `00000000-0000-4000-8000-${String(0xf000 + S.nextFactor++).padStart(12, '0')}`, friendly_name: b.friendly_name ?? '', factor_type: 'totp',
          status: 'unverified', secret: newSecret(), created_at: new Date().toISOString() };
        mine.push(f);
        return json(res, 200, { id: f.id, type: 'totp', friendly_name: f.friendly_name,
          totp: { qr_code: QR_SVG, secret: f.secret, uri: `otpauth://totp/${encodeURIComponent(b.issuer ?? 'stub')}:${encodeURIComponent(a.email)}?secret=${f.secret}&issuer=${encodeURIComponent(b.issuer ?? 'stub')}` } });
      }
      const fm = /^\/auth\/v1\/factors\/([0-9a-f-]{36})(\/challenge|\/verify)?$/.exec(p);
      if (fm) {
        const a = who(req);
        if (!a) return authError(res, 401, 'no_authorization', 'invalid JWT');
        const f = factorsOf(a.id).find((x) => x.id === fm[1]);
        if (!f) return authError(res, 404, 'mfa_factor_not_found', 'Factor not found');
        if (req.method === 'DELETE' && !fm[2]) {
          S.w.calls.push({ fn: 'mfa.unenroll', args: { factorId: f.id }, user: a.id });
          S.factors.set(a.id, factorsOf(a.id).filter((x) => x !== f));
          return json(res, 200, { id: f.id });
        }
        if (req.method === 'POST' && fm[2] === '/challenge') {
          S.w.calls.push({ fn: 'mfa.challenge', args: { factorId: f.id }, user: a.id });
          if (S.mfaLimit > 0) { S.mfaLimit--; return authError(res, 429, 'over_request_rate_limit', 'Request rate limit reached'); }
          return json(res, 200, { id: crypto.randomUUID(), type: 'totp', expires_at: Math.floor(Date.now() / 1000) + 300 });
        }
        if (req.method === 'POST' && fm[2] === '/verify') {
          const b = await body(req);
          S.w.calls.push({ fn: 'mfa.verify', args: { factorId: f.id }, user: a.id });       // never the code
          const now = Date.now();
          const good = [now - 30_000, now, now + 30_000].some((t) => totp(f.secret, t) === String(b.code ?? ''));
          if (!good) return authError(res, 422, 'mfa_verification_failed', 'Invalid TOTP code entered');
          f.status = 'verified';
          return json(res, 200, session(a, 'aal2'));
        }
      }
      if (p === '/rest/v1/staff' && req.method === 'GET') {
        const a = who(req);
        if (!a) return json(res, 401, { code: 'PGRST301', message: 'JWT expired' });
        const want = String(url.searchParams.get('user_id') || '').replace(/^eq\./, '');
        const r = await fakeBackend(S.w, a.id).staffRow(want === a.id ? a.id : '');      // RLS: your own row only
        return json(res, 200, r.data ? [r.data] : []);
      }
      if (p === '/rest/v1/dishes' && req.method === 'GET') {
        const a = who(req);
        if (!a) return json(res, 401, { code: 'PGRST301', message: 'JWT expired' });
        const want = String(url.searchParams.get('id') || '').replace(/^eq\./, '');
        const r = await fakeBackend(S.w, a.id).dishRow(want);                            // RLS: staff read any venue's dishes
        return json(res, 200, r.data ? [r.data] : []);
      }
      if (p.startsWith('/rest/v1/rpc/') && req.method === 'POST') {
        const name = p.slice('/rest/v1/rpc/'.length);
        const args = await body(req);
        if (!req.headers.apikey) return json(res, 401, { message: 'No API key found in request' });
        const a = who(req);
        if (S.requireAal2 && STAFF_RPC.has(name) && a?.aal !== 'aal2') {
          S.w.calls.push({ fn: name, args, user: a?.id ?? null });
          return json(res, 403, { code: '42501', details: null, hint: null, message: 'not_staff' });
        }
        const r = await fakeBackend(S.w, a?.id ?? null).rpc(name, args);
        if (r.error?.name === 'TimeoutError') return undefined;                          // never answers
        if (r.error) return json(res, r.error.status || 500, { code: r.error.code, details: null, hint: null, message: r.error.message });
        // the fake's pictures, in this stub's own project storage (its origin is the config's supabaseUrl)
        return json(res, 200, JSON.parse(JSON.stringify(r.data ?? null).replaceAll(MEDIA_BASE, `http://${req.headers.host}${BUCKET}`)));
      }
      if (p === '/mana/config.js') {
        res.writeHead(200, { 'content-type': MIME['.js'], 'cache-control': 'no-store' });
        return res.end(`window.HALOM_MENUS_CONFIG = ${JSON.stringify({ supabaseUrl: `http://${req.headers.host}`, supabaseKey: 'sb_publishable_stub', env: 'local', schema: 2, realtime: false,
          shortBase: `http://${req.headers.host}/m/`, viewPath: '../view/' })};`);
      }
      if (p === `${BUCKET}cafe/burger_t.png` || p === `${BUCKET}cafe/logo_t.png`) {   // 1×1 pictures; every other one is missing
        res.writeHead(200, { 'content-type': 'image/png', 'cache-control': 'no-store' });
        return res.end(PIXEL);
      }
      if (p.startsWith('/mana/stock/img/') && /^[a-z0-9-]+_t\.jpg$/.test(p.slice('/mana/stock/img/'.length))) {
        const data = await readFile(path.join(root, '../../stock/img', p.slice('/mana/stock/img/'.length)));
        res.writeHead(200, { 'content-type': 'image/jpeg', 'cache-control': 'no-store' });
        return res.end(data);
      }
      if (p === '/mana/ops') { res.writeHead(301, { location: '/mana/ops/' }); return res.end(); }
      if (p.startsWith('/mana/ops/')) {
        const file = path.join(DIST, p.slice('/mana/ops/'.length) || 'index.html');
        if (!file.startsWith(DIST)) { res.writeHead(403); return res.end(); }
        const data = await readFile(file);
        res.writeHead(200, { 'content-type': MIME[path.extname(file)] || 'application/octet-stream', 'cache-control': 'no-store' });
        return res.end(data);
      }
      if (p === '/mana/view/') { res.writeHead(200, { 'content-type': MIME['.html'] }); return res.end(`<!doctype html><title>stub</title><p>the guest menu for ${url.search}</p>`); }
      res.writeHead(404, { 'content-type': 'text/plain' }); res.end('not found');
    } catch (e) {
      if (!res.writableEnded) { res.writeHead(e && e.code === 'ENOENT' ? 404 : 500, { 'content-type': 'text/plain' }); res.end(String(e && e.message)); }
    }
  });
  return {
    get world() { return S.w; },
    reset, server,
    listen: (port = 0) => new Promise((resolve) => server.listen(port, '127.0.0.1', () => resolve(server.address().port))),
    close: () => new Promise((resolve) => { server.closeAllConnections?.(); server.close(() => resolve()); }),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const stub = createStub();
  const port = await stub.listen(Number(process.argv[2]) || 8788);
  console.log(`Mana command center (v2) stub: http://127.0.0.1:${port}/mana/ops/\n  admin, support and a non-staff owner: see ACCOUNTS in test/v2/stub.mjs`);
}
